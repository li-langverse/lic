def glyph_rows(cp: int) -> list[int]:
    return list(GLYPHS.get(cp, _blank()))


def pack_row(row_bits: int, cell_w: int) -> int:
    """Center 5-bit glyph row in cell_w-wide bitmap row."""
    out = 0
    pad_left = (cell_w - FW) // 2
    bits = row_bits & 0x1F
    for col in range(FW):
        if bits & (1 << (FW - 1 - col)):
            out |= 1 << (cell_w - 1 - (col + pad_left))
    return out


def build_table(cell_w: int, cell_rows: int) -> list[list[int]]:
    pad_top = 2 if cell_rows == UI_ROWS else 1
    table: list[list[int]] = []
    for cp in range(FIRST_CP, LAST_CP + 1):
        rows = glyph_rows(cp)
        packed: list[int] = []
        for y in range(cell_rows):
            if y < pad_top or y >= pad_top + FH:
                packed.append(0)
            else:
                packed.append(pack_row(rows[y - pad_top], cell_w))
        table.append(packed)
    return table


def emit_lookup(name: str, cell_w: int, cell_rows: int, table: list[list[int]]) -> str:
    lines = [
        f"def {name}(glyph_index: int, row: int) -> int",
        "  requires glyph_index >= 0",
        "  requires glyph_index < font_atlas_glyph_slot_count()",
        "  requires row >= 0",
        f"  requires row < {cell_rows}",
        "  ensures result >= 0",
        "  decreases glyph_index",
        "=",
    ]
    for idx, rows in enumerate(table):
        lines.append(f"  if glyph_index == {idx}:")
        for r, val in enumerate(rows):
            lines.append(f"    if row == {r}:")
            lines.append(f"      return {val}")
        lines.append("    return 0")
    lines.append("  return 0")
    lines.append("")
    return "\n".join(lines)


def generate_data() -> str:
    ui_table = build_table(8, UI_ROWS)
    mono_table = build_table(7, MONO_ROWS)
    header = (
        "# Generated by scripts/build-font-atlas.py — do not edit by hand.\n"
        "# Bitmap atlas: Inter (UI proportional) + ui-monospace (fixed cell) @ build time.\n"
    )
    parts = [
        header,
        emit_lookup("font_atlas_data_ui_row", 8, UI_ROWS, ui_table),
        emit_lookup("font_atlas_data_mono_row", 7, MONO_ROWS, mono_table),
        "def font_atlas_data_checksum() -> int",
        "  requires true",
        f"  ensures result == {checksum(ui_table, mono_table)}",
        "  decreases 0",
        "=",
        f"  return {checksum(ui_table, mono_table)}",
        "",
    ]
    return "\n".join(parts)


def mirror_into_lib(data_li: str) -> None:
    atlas_src = ATLAS.read_text(encoding="utf-8").strip()
    block = "\n".join(
        [
            "",
            BEGIN,
            "# Mirrored for `import ui` — edit src/font_atlas.li + regenerate.",
            atlas_src,
            "",
            data_li.strip(),
            END,
            "",
        ]
    )
    text = LIB.read_text(encoding="utf-8")
    if BEGIN in text and END in text:
        pre = text.split(BEGIN)[0].rstrip()
        post = text.split(END, 1)[1].lstrip()
        LIB.write_text(pre + block + post, encoding="utf-8")
    else:
        LIB.write_text(text.rstrip() + block, encoding="utf-8")


def generate() -> str:
    return generate_data()


def checksum(ui_table: list[list[int]], mono_table: list[list[int]]) -> int:
    h = hashlib.sha256()
    for table in (ui_table, mono_table):
        for rows in table:
            h.update(bytes(rows))
    return int.from_bytes(h.digest()[:4], "big") & 0x7FFFFFFF


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--verify", action="store_true", help="Fail if generated file is stale")
    args = parser.parse_args()
    content = generate_data()
    if args.verify:
        if not OUT.is_file():
            print(f"FAIL: missing {OUT}", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != content:
            print(f"FAIL: stale {OUT} — run python3 scripts/build-font-atlas.py", file=sys.stderr)
            return 1
        if BEGIN not in LIB.read_text(encoding="utf-8"):
            print(f"FAIL: {LIB.name} missing font atlas mirror — run python3 scripts/build-font-atlas.py", file=sys.stderr)
            return 1
        print(f"build-font-atlas: ok ({OUT.name})")
        return 0
    OUT.write_text(content, encoding="utf-8")
    mirror_into_lib(content)
    print(f"Wrote {OUT} and mirrored into {LIB.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
